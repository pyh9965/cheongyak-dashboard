/**
 * 지역 키에 해당하는 좌표를 반환합니다.
 * @param {string} key - 지역 키 (예: "서울 강남구")
 * @returns {Array|null} 좌표 [lat, lng] 또는 null
 */
function getCoordinates(key) {
    return GEO_COORDINATES[key] || null;
}

// ============================================================================
// 메인 로직
// ============================================================================

const CACHE_PATH = path.join(__dirname, '../public/data/cheongyak-archive.json');

function main() {
    console.log('📍 좌표 데이터 추가 시작...');

    // Read cache
    if (!fs.existsSync(CACHE_PATH)) {
        console.error(`❌ 파일을 찾을 수 없습니다: ${CACHE_PATH}`);
        process.exit(1);
    }

    const data = JSON.parse(fs.readFileSync(CACHE_PATH, 'utf8'));

    if (!data.lists || !Array.isArray(data.lists)) {
        console.error('❌ 잘못된 데이터 형식입니다. lists 배열을 찾을 수 없습니다.');
        process.exit(1);
    }

    let addedCount = 0;
    let skippedCount = 0;
    let failedCount = 0;

    // Process each item
    data.lists.forEach((item, index) => {
        if (item.coordinates) {
            skippedCount++;
            return; // Already has coordinates
        }

        const addr = item.HSSPLY_ADRES;
        if (!addr) {
            failedCount++;
            return;
        }

        const parsed = parseAddress(addr);
        if (parsed) {
            const coords = getCoordinates(parsed.fullKey);
            if (coords) {
                item.coordinates = coords;
                addedCount++;

                // Log first few for debugging
                if (addedCount <= 5) {
                    console.log(`  ✓ [${index}] ${parsed.fullKey} → [${coords[0]}, ${coords[1]}]`);
                }
            } else {
                failedCount++;
                if (failedCount <= 5) {
                    console.log(`  ✗ [${index}] 좌표 없음: ${parsed.fullKey} (주소: ${addr})`);
                }
            }
        } else {
            failedCount++;
            if (failedCount <= 5) {
                console.log(`  ✗ [${index}] 파싱 실패: ${addr}`);
            }
        }
    });

    // Update metadata
    if (!data.metadata) {
        data.metadata = {};
    }
    data.metadata.geocodedCount = addedCount;
    data.metadata.lastGeocodedAt = new Date().toISOString();

    // Save
    fs.writeFileSync(CACHE_PATH, JSON.stringify(data, null, 2), 'utf8');

    console.log('\n📊 처리 결과:');
    console.log(`  - 좌표 추가: ${addedCount}건`);
    console.log(`  - 이미 존재: ${skippedCount}건`);
    console.log(`  - 실패: ${failedCount}건`);
    console.log(`  - 전체: ${data.lists.length}건`);
    console.log(`\n✅ 좌표 추가 완료!`);
}

// Run
try {
    main();
} catch (error) {
    console.error('❌ 오류 발생:', error);
    process.exit(1);
}
